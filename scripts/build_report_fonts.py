"""Rebuild engine/report_fonts.css: the fonts the evidence report embeds, so it looks the same offline
and in print and makes no network requests.

    python scripts/build_report_fonts.py COURIER_PRIME_DIR JETBRAINS_MONO_DIR

COURIER_PRIME_DIR holds CourierPrime-Regular.ttf and CourierPrime-Bold.ttf
  (https://github.com/google/fonts/tree/main/ofl/courierprime).
JETBRAINS_MONO_DIR holds JetBrainsMono-Regular and -Bold as .ttf or .woff2
  (https://github.com/JetBrains/JetBrainsMono, also bundled with Hermes Desktop).
Both families are under the SIL Open Font License 1.1; see licenses/.

Needs fonttools and brotli (pip install fonttools brotli). Only Latin, Latin-1 and the few symbols
the report draws are kept; anything else falls back to the system fonts in the CSS stacks.
"""

from __future__ import annotations

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "engine" / "report_fonts.css"
TEXT = ("".join(chr(c) for c in range(0x20, 0x7F)) + "".join(chr(c) for c in range(0xA0, 0x100))
        + "✓✗–—·“”‘’…→←●│─╭╰≤≥×•")
FACES = [  # (family, weight, file stem, which source dir)
    ("RP Courier Prime", 400, "CourierPrime-Regular", 0),
    ("RP Courier Prime", 700, "CourierPrime-Bold", 0),
    ("RP JetBrains Mono", 400, "JetBrainsMono-Regular", 1),
    ("RP JetBrains Mono", 700, "JetBrainsMono-Bold", 1),
]


def find(directory: Path, stem: str) -> Path:
    for ext in (".ttf", ".woff2", ".otf"):
        p = directory / (stem + ext)
        if p.is_file():
            return p
    sys.exit(f"missing {stem}.ttf/.woff2 in {directory}")


def woff2_subset(path: Path) -> bytes:
    font = TTFont(path)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "calt", "tnum"]
    opts.name_IDs = [0, 1, 2, 13, 14]  # keep copyright and license entries
    sub = subset.Subsetter(opts)
    sub.populate(text=TEXT)
    sub.subset(font)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    dirs = [Path(sys.argv[1]), Path(sys.argv[2])]
    rules = []
    for family, weight, stem, src in FACES:
        data = woff2_subset(find(dirs[src], stem))
        b64 = base64.b64encode(data).decode("ascii")
        rules.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};'
                     f'font-display:swap;src:url(data:font/woff2;base64,{b64}) format("woff2")}}')
        print(f"{stem}: {len(data):,} bytes woff2")
    header = ("/* Generated by scripts/build_report_fonts.py. Do not edit by hand.\n"
              "   Courier Prime (c) 2015 The Courier Prime Project Authors; JetBrains Mono (c) 2020 The JetBrains\n"
              "   Mono Project Authors. Both under the SIL Open Font License 1.1: licenses/OFL-*.txt.\n"
              "   Subsets for Latin and Latin-1 only. */\n")
    OUT.write_text(header + "\n".join(rules) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
